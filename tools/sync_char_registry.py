#!/usr/bin/env python3
"""Generate the TypeScript character registry from the JSON character source of truth."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CHARS = ROOT / 'packages' / 'anchor-core' / 'src' / 'chars'
TARGET = CHARS / 'index.ts'
KEY = re.compile(r'^[A-Za-z_][A-Za-z0-9_]*$')


def main():
    keys = [path.stem for path in sorted(CHARS.glob('*.json'))]
    invalid = [key for key in keys if not KEY.fullmatch(key)]
    if invalid:
        raise SystemExit(f'角色 key 必须是 TypeScript 标识符：{", ".join(invalid)}')
    imports = '\n'.join(f"import {key} from './{key}.json';" for key in keys)
    registry = ', '.join(keys)
    TARGET.write_text(
        '// Generated by tools/sync_char_registry.py. Do not edit by hand.\n'
        f'{imports}\n\n'
        f'export const CHARACTER_DATA = {{{registry}}};\n'
        'export type CharacterKey = keyof typeof CHARACTER_DATA;\n',
        encoding='utf-8',
    )
    print(f'已注册 {len(keys)} 个角色：{", ".join(keys)}')


if __name__ == '__main__':
    main()
